void require(bool ok, const std::string& text) { if (!ok) throw std::runtime_error(text); }
static std::vector<std::string> split(const std::string& s, char delimiter) {
    std::vector<std::string> result; std::istringstream in(s); std::string item;
    while (std::getline(in, item, delimiter)) result.push_back(item);
    return result;
}
void validateVersion(const std::string& v) {
    require(std::regex_match(v, std::regex("v(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)(-[0-9A-Za-z]+([.-][0-9A-Za-z]+)*)?")) && v.size() < 128,
            "Invalid version: " + v);
}
static int numeric(const std::string& a, const std::string& b) {
    if (a.size() != b.size()) return a.size() < b.size() ? -1 : 1;
    return a == b ? 0 : a < b ? -1 : 1;
}
int compareVersions(const std::string& a, const std::string& b) {
    validateVersion(a); validateVersion(b);
    auto ai = a.find('-'), bi = b.find('-');
    auto ac = split(a.substr(1, ai == a.npos ? ai : ai - 1), '.');
    auto bc = split(b.substr(1, bi == b.npos ? bi : bi - 1), '.');
    for (int i = 0; i < 3; ++i) { int n = numeric(ac[i], bc[i]); if (n) return n; }
    if (ai == a.npos || bi == b.npos) return ai == bi ? 0 : ai == a.npos ? 1 : -1;
    auto ap = split(a.substr(ai + 1), '.'), bp = split(b.substr(bi + 1), '.');
    for (size_t i = 0; i < std::min(ap.size(), bp.size()); ++i) {
        bool an = ap[i].find_first_not_of("0123456789") == ap[i].npos;
        bool bn = bp[i].find_first_not_of("0123456789") == bp[i].npos;
        int n = an && bn ? numeric(ap[i], bp[i]) : an != bn ? (an ? -1 : 1) : ap[i] == bp[i] ? 0 : ap[i] < bp[i] ? -1 : 1;
        if (n) return n;
    }
    return ap.size() == bp.size() ? 0 : ap.size() < bp.size() ? -1 : 1;
}
static std::string lower(std::string s) {
    std::transform(s.begin(), s.end(), s.begin(), [](unsigned char c) { return char(std::tolower(c)); }); return s;
}
void validatePath(const std::string& value, bool android) {
    require(!value.empty() && value.size() < 220, "Invalid update path length");
    std::string path = value;
    if (android) { require(path[0] == '/', "Android path must start with /"); path.erase(0, 1); }
    require(!path.empty() && path[0] != '/' && path.back() != '/' && path.find("//") == path.npos, "Invalid update path: " + value);
    for (unsigned char c : path) require(c >= 32 && c < 127 && std::string("\\:*?\"<>|").find(c) == std::string::npos, "Unsupported update path: " + value);
    for (const auto& part : split(path, '/')) {
        require(part != "." && part != ".." && part.back() != '.' && part.back() != ' ', "Unsafe update path: " + value);
        auto stem = lower(part.substr(0, part.find('.')));
        require(!std::regex_match(stem, std::regex("con|prn|aux|nul|com[0-9]|lpt[0-9]")), "Reserved path: " + value);
    }
    if (!android) require(lower(path).rfind(".kemu-update", 0) != 0, "Reserved updater path");
}
void validateHash(const std::string& hash) { require(std::regex_match(hash, std::regex("[0-9a-f]{64}")), "Invalid SHA-256"); }
Plan resolve(const Json& history, const std::string& current) {
    validateVersion(current);
    require(history.at("schema_version") == 1 && history.at("releases").is_array(), "Unsupported version history");
    std::vector<Release> releases; std::set<std::string> versions;
    bool found = false;
    for (const auto& item : history.at("releases")) {
        Release release; release.version = item.at("version").get<std::string>(); validateVersion(release.version);
        require(versions.insert(release.version).second, "Duplicate version history entry");
        found |= release.version == current;
        release.files = item.at("files").get<std::vector<std::string>>();
        std::set<std::string> paths;
        for (const auto& path : release.files) {
            bool android = !path.empty() && path[0] == '/'; validatePath(path, android);
            require(paths.insert(android ? path : lower(path)).second, "Duplicate update file");
            require(android || (lower(path) != "version.txt" && lower(path) != "system-img/verifiedbootparams.textproto" && lower(path) != "system-img/system.img"), "Image/VERSION files must be generated by the updater");
        }
        releases.push_back(std::move(release));
    }
    require(found, "Local version is absent from version-history.json; download the full release: " + std::string(ReleasesUrl));
    std::sort(releases.begin(), releases.end(), [](const Release& a, const Release& b) { return compareVersions(a.version, b.version) < 0; });
    Plan plan; plan.current = current; plan.target = current;
    for (const auto& r : releases) if (compareVersions(r.version, plan.target) > 0 && (current.find('-') != current.npos || r.version.find('-') == r.version.npos)) plan.target = r.version;
    std::map<std::string, std::string> casing;
    for (const auto& r : releases) if (compareVersions(r.version, current) > 0 && compareVersions(r.version, plan.target) <= 0) {
        for (const auto& path : r.files) {
            auto key = path[0] == '/' ? path : lower(path);
            auto prev = casing.find(key);
            require(prev == casing.end() || prev->second == path, "Path casing changed across releases: " + path);
            casing[key] = path; plan.files[path] = r;
        }
    }
    return plan;
}
std::string readText(const fs::path& path, size_t limit) {
    require(fs::is_regular_file(path) && fs::file_size(path) <= limit, "Missing or oversized file: " + path.u8string());
    std::ifstream in(path, std::ios::binary); require(bool(in), "Cannot read: " + path.u8string());
    std::string result((std::istreambuf_iterator<char>(in)), {}); require(!in.bad(), "Read failed"); return result;
}
std::string readVersion(const fs::path& root) {
    std::string v;
    try { v = readText(root / "VERSION.txt", 256); } catch (...) { throw std::runtime_error("VERSION.txt is missing or unreadable. Download the full release: " + std::string(ReleasesUrl)); }
    if (v.rfind("\xef\xbb\xbf", 0) == 0) v.erase(0, 3);
    if (!v.empty() && v.back() == '\n') v.pop_back();
    if (!v.empty() && v.back() == '\r') v.pop_back();
    validateVersion(v); return v;
}
std::string sha256(const fs::path& path) {
    BCRYPT_ALG_HANDLE alg = nullptr; BCRYPT_HASH_HANDLE hash = nullptr;
    require(BCryptOpenAlgorithmProvider(&alg, BCRYPT_SHA256_ALGORITHM, nullptr, 0) >= 0, "Cannot open SHA-256");
    struct Cleanup { BCRYPT_ALG_HANDLE a; BCRYPT_HASH_HANDLE& h; ~Cleanup() { if (h) BCryptDestroyHash(h); BCryptCloseAlgorithmProvider(a,0); } } cleanup{alg, hash};
    require(BCryptCreateHash(alg, &hash, nullptr, 0, nullptr, 0, 0) >= 0, "Cannot create SHA-256");
    std::ifstream in(path, std::ios::binary); require(bool(in), "Cannot hash: " + path.u8string());
    std::vector<char> data(1024 * 1024);
    while (in) { in.read(data.data(), data.size()); if (in.gcount()) require(BCryptHashData(hash, reinterpret_cast<PUCHAR>(data.data()), ULONG(in.gcount()), 0) >= 0, "SHA-256 failed"); }
    require(in.eof(), "Cannot finish reading file");
    unsigned char digest[32]; require(BCryptFinishHash(hash, digest, 32, 0) >= 0, "SHA-256 failed");
    std::string result; const char* hex = "0123456789abcdef";
    for (auto byte : digest) { result += hex[byte >> 4]; result += hex[byte & 15]; } return result;
}
void writeText(const fs::path& path, const std::string& data) {
    fs::create_directories(path.parent_path()); auto temp = path; temp += L".tmp";
    HANDLE file = CreateFileW(temp.c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
    require(file != INVALID_HANDLE_VALUE, "Cannot create: " + temp.u8string());
    DWORD written = 0; bool ok = WriteFile(file, data.data(), DWORD(data.size()), &written, nullptr) && written == data.size() && FlushFileBuffers(file);
    CloseHandle(file); require(ok, "Cannot persist file");
    require(MoveFileExW(temp.c_str(), path.c_str(), MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH), "Cannot commit file: " + path.u8string());
}
void writeJson(const fs::path& path, const Json& value) { writeText(path, value.dump(2) + "\n"); }
Json readJson(const fs::path& path) { return Json::parse(readText(path)); }
void safePath(const fs::path& root, const std::string& relative) {
    validatePath(relative);
    auto current = root;
    require(fs::is_directory(root) && !(GetFileAttributesW(root.c_str()) & FILE_ATTRIBUTE_REPARSE_POINT), "Unsafe root directory");
    for (const auto& part : split(relative, '/')) {
        current /= fs::u8path(part); DWORD attr = GetFileAttributesW(current.c_str());
        if (attr != INVALID_FILE_ATTRIBUTES) require(!(attr & FILE_ATTRIBUTE_REPARSE_POINT), "Reparse point in update path: " + current.u8string());
    }
}
std::map<std::string, std::string> parseChecksums(const std::string& text) {
    std::map<std::string, std::string> result; std::istringstream in(text); std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back(); if (line.empty()) continue;
        require(line.size() > 66 && line[64] == ' ' && (line[65] == ' ' || line[65] == '*'), "Invalid sha256sum.txt line");
        auto hash = line.substr(0,64), path = line.substr(66); validateHash(hash); validatePath(path);
        require(path.rfind("Windows/", 0) == 0 || path.rfind("Android/", 0) == 0, "Invalid checksum path");
        require(result.emplace(path, hash).second, "Duplicate checksum path");
    }
    require(!result.empty(), "Empty sha256sum.txt"); return result;
}
void clearUpdateDirectory(const fs::path& root, const fs::path& directory) {
    auto base = fs::absolute(root / ".kemu-update").lexically_normal();
    auto target = fs::absolute(directory).lexically_normal();
    auto relative = target.lexically_relative(base);
    require(target == base || (!relative.empty() && *relative.begin() != ".."), "Cleanup outside update directory");
    require(!(GetFileAttributesW(root.c_str()) & FILE_ATTRIBUTE_REPARSE_POINT), "Unsafe installation root");
    if (!fs::exists(base)) return;
    require(!(GetFileAttributesW(base.c_str()) & FILE_ATTRIBUTE_REPARSE_POINT), "Unsafe update directory");
    if (target != base) safePath(base, relative.generic_u8string());
    if (!fs::exists(target)) return;
    for (const auto& item : fs::recursive_directory_iterator(target))
        require(!(GetFileAttributesW(item.path().c_str()) & FILE_ATTRIBUTE_REPARSE_POINT), "Unsafe update cache entry");
    fs::remove_all(target);
}
Plan prepareUpdateTask(const fs::path& root, const Json& history) {
    require(!fs::exists(root / ".kemu-update-pending"), "Recover unfinished installation before checking updates");
    auto plan = resolve(history, readVersion(root));
    auto stage = root / ".kemu-update";
    bool reuse = false;
    if (fs::exists(stage)) {
        safePath(stage, "task.json");
        try { auto task = readJson(stage / "task.json"); reuse = task.at("from") == plan.current && task.at("to") == plan.target; } catch (...) {}
        if (!reuse) clearUpdateDirectory(root, stage);
    }
    fs::create_directories(stage);
    if (reuse && fs::exists(stage / "journal.json")) {
        auto state = readJson(stage / "journal.json").at("state").get<std::string>();
        require(state != "applying", "Unfinished installation journal needs recovery");
        if (state == "rolled_back") fs::remove(stage / "journal.json");
    }
    writeJson(stage / "history.json", history);
    writeJson(stage / "task.json", {{"from",plan.current},{"to",plan.target}});
    fs::remove(root / ".kemu-update-ready");
    return plan;
}
void saveDownloadedUpdate(const fs::path& stage, const Plan& plan) {
    Json files = Json::array();
    for (const auto& [path, release] : plan.files) {
        auto relative = path[0] == '/' ? "android" + path : "payload/" + path;
        safePath(stage, relative);
        auto packed = path[0] == '/' ? "Android" + path : "Windows/" + path;
        auto expected = parseChecksums(readText(stage / release.version / "sha256sum.txt")).at(packed);
        require(sha256(stage / fs::u8path(relative)) == expected, "Downloaded payload changed");
        files.push_back({{"path", relative}, {"sha256", expected}});
    }
    writeJson(stage / "downloaded.json", {{"schema_version",1}, {"from",plan.current}, {"to",plan.target}, {"files",files}});
}
bool loadDownloadedUpdate(const fs::path& root, fs::path& stage, Plan& plan) {
    auto cached = root / ".kemu-update";
    if (!fs::exists(cached / "downloaded.json")) return false;
    try {
        safePath(cached, "downloaded.json");
        auto record = readJson(cached / "downloaded.json");
        auto current = readVersion(root);
        require(record.at("schema_version") == 1 && record.at("from") == current, "Stale downloaded update");
        auto selected = resolve(readJson(cached / "history.json"), current);
        require(record.at("to") == selected.target && compareVersions(selected.target, current) > 0, "Invalid downloaded target");
        std::map<std::string, std::string> expected;
        for (const auto& [path, release] : selected.files) expected[path[0] == '/' ? "android" + path : "payload/" + path] = {};
        require(record.at("files").is_array() && record.at("files").size() == expected.size(), "Incomplete downloaded update");
        for (const auto& file : record.at("files")) {
            auto path = file.at("path").get<std::string>(), hash = file.at("sha256").get<std::string>();
            require(expected.erase(path) == 1, "Unexpected downloaded file");
            validateHash(hash); safePath(cached, path);
            require(sha256(cached / fs::u8path(path)) == hash, "Downloaded file hash mismatch");
        }
        require(expected.empty(), "Missing downloaded file");
        stage = cached; plan = std::move(selected); return true;
    } catch (...) {
        fs::remove(cached / "downloaded.json");
        return false;
    }
}

