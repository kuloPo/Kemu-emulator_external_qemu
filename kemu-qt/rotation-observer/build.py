"""Build the embedded rotation observer with the emulator's prebuilt JDK and SDK."""

import argparse
import base64
import hashlib
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser()
    for name in ("java", "javac", "d8", "android-jar", "output"):
        parser.add_argument("--" + name, required=True)
    args = parser.parse_args()
    source = Path(__file__).resolve().parent
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="rotation-", dir=output.parent) as temporary:
        work = Path(temporary)
        classes = work / "classes"
        classes.mkdir()
        subprocess.run([args.javac, "-source", "8", "-target", "8", "-Xlint:-options",
                        "-classpath", args.android_jar, "-d", str(classes),
                        str(source / "IRotationWatcher.java"),
                        str(source / "RotationObserver.java")], check=True)
        # Exclude the compile-time android.view stub from the deployed dex.
        application_classes = sorted((classes / "org").rglob("*.class"))
        subprocess.run([args.java, "-cp", args.d8, "com.android.tools.r8.D8",
                        "--min-api", "26", "--lib", args.android_jar,
                        "--classpath", str(classes), "--output", str(work)]
                       + [str(path) for path in application_classes], check=True)
        dex = (work / "classes.dex").read_bytes()
        encoded = base64.b64encode(dex).decode("ascii")
        lines = ['"' + encoded[i:i + 100] + '"' for i in range(0, len(encoded), 100)]
        header = ('// Generated by rotation-observer/build.py.\n#pragma once\n'
                  'namespace kemu {\ninline constexpr char kRotationObserverDex[] =\n'
                  + "\n".join(lines) + ';\ninline constexpr char kRotationObserverHash[] = "'
                  + hashlib.sha256(dex).hexdigest() + '";\n}  // namespace kemu\n')
        output.write_text(header, encoding="ascii")


if __name__ == "__main__":
    main()
